// ESM loader hooks for scripts/security-checks.mts — test plumbing only,
// no application logic:
//  1. map the app's `@/…` path alias onto src/… (adding the file extension)
//  2. resolve extensionless relative imports inside src/ (TypeScript style)
//  3. serve *.json as an ES module (Node otherwise demands an import attribute)
//  4. resolve bare `next/server` (a CJS-style specifier Next.js supports)
//  5. stub src/lib/db.ts — the Prisma data layer is the boundary under test,
//     not the subject: the route handlers' own logic stays 100% real. This
//     also keeps the suite runnable with no database and no Prisma engine.
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '..');

export async function resolve(specifier, context, nextResolve) {
  if (specifier === 'next/server' || specifier === 'next/headers') {
    const p = require.resolve(`${specifier}.js`);
    return { url: pathToFileURL(p).href, shortCircuit: true, format: 'commonjs' };
  }
  if (specifier.startsWith('@/')) {
    const base = specifier.slice(2);
    for (const ext of ['.ts', '.tsx', '.json', '']) {
      const p = path.join(ROOT, 'src', base + ext);
      if (existsSync(p)) return { url: pathToFileURL(p).href, shortCircuit: true };
    }
  }
  if ((specifier.startsWith('./') || specifier.startsWith('../')) && !path.extname(specifier)) {
    const from = context.parentURL ? fileURLToPath(context.parentURL) : ROOT;
    const base = path.resolve(path.dirname(from), specifier);
    for (const ext of ['.ts', '.tsx', '.json', '']) {
      if (existsSync(base + ext)) return { url: pathToFileURL(base + ext).href, shortCircuit: true };
    }
  }
  return nextResolve(specifier, context);
}

const STUB_DB = `
// generated by scripts/security-checks-loader.mjs — plain objects so the
// harness can install per-test spies (db.post.update = …) and read them back.
export const db = {
  post: {}, comment: {}, category: {}, tag: {}, postTag: {}, service: {},
  project: {}, siteSetting: {}, contactMessage: {}, chatSession: {},
  chatMessage: {}, kbChunk: {}, adminUser: {}, aiJob: {},
  $executeRawUnsafe: async () => 0,
  $queryRawUnsafe: async () => [],
};
`;

export async function load(url, context, nextLoad) {
  if (url.startsWith('file:') && url.endsWith('/src/lib/db.ts')) {
    return { format: 'module', source: STUB_DB, shortCircuit: true };
  }
  if (url.startsWith('file:') && url.endsWith('.json')) {
    const text = await readFile(fileURLToPath(url), 'utf8');
    return { format: 'module', source: `export default ${text};\n`, shortCircuit: true };
  }
  return nextLoad(url, context);
}
